import { useEffect, useRef, useState } from 'react';
import { ShieldWorkspace } from './ShieldWorkspace';
import { validateDimensions, validateFile } from './lib/image';

type Selection = { url: string; name: string; width: number; height: number };

function ImageSlot({ title, description, id }: { title: string; description: string; id: string }) {
  const [selection, setSelection] = useState<Selection | null>(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const request = useRef(0);
  const input = useRef<HTMLInputElement>(null);
  useEffect(() => () => { request.current += 1; }, []);
  useEffect(() => () => { if (selection) URL.revokeObjectURL(selection.url); }, [selection]);

  async function select(file: File | undefined) {
    if (!file) return;
    const current = ++request.current;
    setError('');
    setSelection(null);
    setBusy(false);
    const invalid = validateFile(file);
    if (invalid) { setError(invalid); return; }
    setBusy(true);
    const url = URL.createObjectURL(file);
    try {
      const image = new Image();
      image.src = url;
      await image.decode();
      if (current !== request.current) { URL.revokeObjectURL(url); return; }
      const invalidSize = validateDimensions(image.naturalWidth, image.naturalHeight);
      if (invalidSize) throw new Error(invalidSize);
      setSelection({ url, name: file.name, width: image.naturalWidth, height: image.naturalHeight });
    } catch (reason) {
      URL.revokeObjectURL(url);
      if (current === request.current) setError(reason instanceof Error && reason.message.startsWith('Choose') ? reason.message : 'This image could not be read. Try another PNG or JPEG.');
    } finally {
      if (current === request.current) setBusy(false);
    }
  }

  return <article className="image-card">
    <h3>{title}</h3><p id={`${id}-help`}>{description}</p>
    <div className="preview">{selection ? <img src={selection.url} alt={`${title}: ${selection.name}`} /> : <span>{busy ? 'Reading image…' : 'Your image goes here'}</span>}</div>
    <label className="file-label" htmlFor={id}>Choose image</label>
    <input ref={input} id={id} type="file" accept="image/png,image/jpeg" aria-describedby={`${id}-help ${id}-error`} onChange={event => { void select(event.target.files?.[0]); event.target.value = ''; }} />
    <p className="metadata">{selection ? `${selection.name} · ${selection.width} × ${selection.height}` : 'PNG or JPEG · up to 10 MB / 24 MP'}</p>
    {selection && <button className="text-button" onClick={() => { ++request.current; setSelection(null); setError(''); input.current?.focus(); }}>Remove image</button>}
    <p id={`${id}-error`} role="alert" className="error">{error}</p>
  </article>;
}

export default function App() {
  return <div className="shell">
    <header><a href="#" className="wordmark">viel<span>✳</span></a><a href="#lab">Open Shield Lab ↗</a></header>
    <main>
      <section className="hero" aria-labelledby="headline">
        <span className="eyebrow">YOUR PICTURES. YOUR INTENT.</span>
        <h1 id="headline">Keep the picture.<br/><span>Disrupt the edit.</span></h1>
        <p>Exploring subtle pixel changes that preserve how your photo looks while making AI manipulation harder.</p>
        <a className="primary" href="#workspace">Explore the workspace ↓</a>
        <div className="status"><span className="dot"/> Experimental image shielding · effectiveness must be tested</div>
      </section>
      <section id="workspace" aria-labelledby="workspace-title">
        <div className="section-heading"><span className="eyebrow">01 / YOUR IMAGE</span><h2 id="workspace-title">Start with the original.</h2><p>Preview locally, then explicitly choose whether to send your image to the configured shielding service.</p></div>
        <ShieldWorkspace />
      </section>
      <section id="lab" aria-labelledby="lab-title">
        <div className="section-heading"><span className="eyebrow">02 / SHIELD LAB</span><h2 id="lab-title">See the difference. Test the claim.</h2><p>Bring real outputs from a separate experiment. Use the same editor, prompt, settings, and seed where available. These are user-supplied images, not verified results.</p></div>
        <div className="lab-grid">
          <ImageSlot id="candidate" title="Candidate shielded photo" description="A candidate generated by an external protection engine." />
          <ImageSlot id="clean-edit" title="Edit from the original" description="The AI editor’s output using the unprotected image." />
          <ImageSlot id="shield-edit" title="Edit from the candidate" description="The same requested edit using the candidate image." />
        </div>
        <p className="note">Visible differences alone do not prove protection. Repeat trials and test resizing, JPEG compression, and screenshots. A successful test on one model does not establish protection on another.</p>
      </section>
    </main>
    <footer><span className="wordmark">viel</span><p>Experimental by design. Evidence before promises.</p></footer>
  </div>;
}
